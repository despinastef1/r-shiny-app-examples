# Load R packages
library(shiny)
library(shinythemes)


  # Define UI
  #rstudio.github.io/shinythemes
  ui <- fluidPage(theme = shinytheme("cerulean"), 
    navbarPage(
      # theme = "cerulean",  # <--- To use a theme, uncomment this
      "My first app",
      tabPanel("Navbar 1",
               sidebarPanel(
                 tags$h3("Input:"),
                 #https://dreamrs.github.io/shinyWidgets/index.html
                 textInput("txt1", "Given Name:", ""),       #txt1 is sent to the server
                 textInput("txt2", "Surname:", ""),          #txt2 is sent to the server
                 
               ), # sidebarPanel
               mainPanel(
                            h1("Header 1"),
                            
                            h4("Output 1"),
                            verbatimTextOutput("txtout"),  #txtout is generated by the server

               ) # mainPanel
               
      ), # Navbar 1, tabPanel
      tabPanel("Navbar 2", "This panel is intentionally left blank"),
      tabPanel("Navbar 3", "This panel is intentionally left blank")
  
    ) # navbarPage
  ) # fluidPage

  
  # Define server function  
  server <- function(input, output) {
    
    #render functions at https://shiny.posit.co/r/getstarted/build-an-app/reactive-flow/render-functions.html
    output$txtout <- renderText({
      paste( input$txt1, input$txt2, sep = " " )
    })
  } # server
  

  # Create Shiny object
  shinyApp(ui = ui, server = server)
  
